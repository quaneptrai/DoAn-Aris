"""Assemble a minimal FastAPI Cloud bundle for the resume parser service.

The resume-engine folder also holds the TypeScript Studio (src/, node_modules/, tests/), so it is
not deployed as-is. This script copies only what the parser needs into an output folder:

    out/
      main.py               FastAPI Cloud entrypoint (refuses to start without RESUME_PARSER_API_KEY);
                            the FastAPI Cloud runtime only auto-detects main.py, not [tool.fastapi]
      pyproject.toml        dependencies from server/requirements.txt + [tool.fastapi] entrypoint
      server/*.py           app.py, layout_parser.py, ocr_sidecar.py (no tests)
      contracts/            canonical-resume.schema.json (app.py loads it from ../contracts)

The output keeps its .fastapicloud/ link between builds. Default output: ~/.aris/parser-deploy.
It must live OUTSIDE this git repository: the FastAPI Cloud CLI collects files with rignore, which
honours the repository's .gitignore (.local/ is ignored), so a bundle inside the repo uploads nothing.

Usage (from the repository root):
    python ArisSkyve/resume-engine/build-parser-deploy.py [out_dir]
    uvx --from "fastapi[standard]" fastapi deploy ~/.aris/parser-deploy
"""
import shutil
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parent
REPO = ENGINE.parents[1]
DEFAULT_OUT = Path.home() / '.aris' / 'parser-deploy'
SERVER_FILES = ('app.py', 'layout_parser.py', 'ocr_sidecar.py')
CONTRACT = Path('contracts') / 'canonical-resume.schema.json'

ENTRYPOINT = '''"""FastAPI Cloud entrypoint for the Aris resume parser (generated by build-parser-deploy.py)."""
import os
import sys
from pathlib import Path

# Outside localhost the parser must only answer Aris: fail closed when the shared key is missing.
if len(os.environ.get('RESUME_PARSER_API_KEY', '').strip()) < 32:
    raise RuntimeError('Set RESUME_PARSER_API_KEY (32+ characters) before deploying the resume parser.')

sys.path.insert(0, str(Path(__file__).resolve().parent / 'server'))
from app import app  # noqa: E402,F401
'''


def dependencies():
    lines = (ENGINE / 'server' / 'requirements.txt').read_text(encoding='utf-8').splitlines()
    deps = [line.strip() for line in lines if line.strip() and not line.lstrip().startswith('#')]
    # fastapi[standard] brings the FastAPI CLI/server that FastAPI Cloud runs.
    return [('fastapi[standard]' + dep[len('fastapi'):]) if dep.startswith('fastapi') and not dep.startswith('fastapi[') else dep
            for dep in deps]


def build(out: Path):
    if out == REPO or REPO in out.parents:
        raise SystemExit(f'{out} is inside the git repository; FastAPI Cloud would upload an empty bundle. Use a folder outside {REPO}.')
    out.mkdir(parents=True, exist_ok=True)
    for child in out.iterdir():
        if child.name == '.fastapicloud':
            continue
        shutil.rmtree(child) if child.is_dir() else child.unlink()
    (out / 'server').mkdir()
    for name in SERVER_FILES:
        shutil.copy2(ENGINE / 'server' / name, out / 'server' / name)
    (out / CONTRACT).parent.mkdir()
    shutil.copy2(ENGINE / CONTRACT, out / CONTRACT)
    (out / 'main.py').write_text(ENTRYPOINT, encoding='utf-8')
    deps = ',\n'.join(f'    "{dep}"' for dep in dependencies())
    (out / 'pyproject.toml').write_text(
        '[project]\n'
        'name = "aris-resume-parser"\n'
        'version = "1.0.0"\n'
        'description = "Aris Resume Studio parser (PDF layout import and document parsing)"\n'
        'requires-python = ">=3.11"\n'
        f'dependencies = [\n{deps},\n]\n\n'
        '[build-system]\n'
        'requires = ["setuptools>=69"]\n'
        'build-backend = "setuptools.build_meta"\n\n'
        '# The service runs from the deployed folder (main.py, server/, contracts/); nothing is installed\n'
        '# as a package. Without this, setuptools flat-layout discovery fails on server/ + contracts/.\n'
        '[tool.setuptools]\n'
        'packages = []\n'
        'py-modules = []\n\n'
        '[tool.uv]\n'
        'package = false\n\n'
        '[tool.fastapi]\n'
        'entrypoint = "main:app"\n', encoding='utf-8')
    return out


if __name__ == '__main__':
    target = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_OUT
    print(build(target))
